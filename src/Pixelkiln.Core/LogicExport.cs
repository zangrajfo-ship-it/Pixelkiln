using System.Globalization;
using System.Text;
using static Pixelkiln.Core.GodotExport;

namespace Pixelkiln.Core;

/// <summary>
/// GDScript from a logic graph (spec: .ai/context/logic.md): one function per node, Timer nodes for timers, the areas'
/// body_entered signal, a distance check for touches. The script is for the game; Pixelkiln never runs it.
/// </summary>
public static class LogicExport
{
    public const double TouchRadius = 12;

    /// <param name="res">res:// path of an exported asset (sounds as .wav, scenes as .tscn), or null when not exported.</param>
    /// <param name="player">Node name of the player in the level (null = no player: area and touch events never fire).</param>
    public static string Gd(LogicGraph g, string name, Func<Guid, string?> res, string? player)
    {
        var sb = new StringBuilder();
        void L(int indent, string line) => sb.Append('\t', indent).Append(line).Append('\n');
        string Fn(LogicNode n) => "_n_" + new string([.. n.Id.Select(c => char.IsAsciiLetterOrDigit(c) ? c : '_')]);
        string Num(LogicNode n, string key, double fallback = 0) => F(n.Number(key, fallback));
        var links = g.Links.GroupBy(l => l.From).ToDictionary(x => x.Key, x => x.ToList());
        IEnumerable<LogicNode> Next(LogicNode n, string port) => (links.GetValueOrDefault(n.Id) ?? []).Where(l => l.Port == port).Select(l => g.Node(l.To)).OfType<LogicNode>();
        void Calls(int indent, LogicNode n, string port)
        {
            var next = Next(n, port).ToList();
            if (next.Count == 0) L(indent, "pass");
            foreach (var t in next) L(indent, $"{Fn(t)}()");
        }

        L(0, "extends Node");
        L(0, $"## Generated by Pixelkiln from “{name}”. Change the graph in Pixelkiln and export again.");
        L(0, "");
        L(0, "var vars := {}");
        L(0, "var items := {}");
        L(0, "var _touching := {}");
        L(0, "@onready var level: Node = get_parent()");
        L(0, "");
        L(0, "func _obj(n: String) -> Node:");
        L(1, "return level.find_child(n, true, false)");
        L(0, "");
        L(0, "func _player() -> Node:");
        L(1, player is null ? "return null" : $"return _obj({Q(NodeName(player))})");
        L(0, "");
        L(0, "func _ready() -> void:");
        foreach (var t in g.Nodes.Where(n => n.Kind == LogicKind.Timer))
        {
            string v = "t" + Fn(t);
            L(1, $"var {v} := Timer.new()");
            L(1, $"{v}.wait_time = {F(double.Parse(Num(t, "ms", 1000), CultureInfo.InvariantCulture) / 1000)}");
            L(1, $"{v}.one_shot = {(t.P("repeat") == "yes" ? "false" : "true")}");
            L(1, $"{v}.autostart = true");
            L(1, $"add_child({v})");
            L(1, $"{v}.timeout.connect({Fn(t)})");
        }
        foreach (var a in g.Nodes.Where(n => n.Kind == LogicKind.EnterArea))
        {
            string v = "a" + Fn(a);
            L(1, $"var {v} := _obj({Q(NodeName(a.P("area")))})");
            L(1, $"if {v} is Area2D:");
            L(2, $"{v}.body_entered.connect(_entered{Fn(a)})");
        }
        foreach (var s in g.Nodes.Where(n => n.Kind == LogicKind.Start)) L(1, $"{Fn(s)}.call_deferred()");
        L(1, "pass");
        L(0, "");

        foreach (var a in g.Nodes.Where(n => n.Kind == LogicKind.EnterArea))
        {
            L(0, $"func _entered{Fn(a)}(body: Node) -> void:");
            L(1, "if body == _player():");
            L(2, $"{Fn(a)}()");
            L(0, "");
        }

        var touches = g.Nodes.Where(n => n.Kind == LogicKind.Touch).ToList();
        if (touches.Count > 0)
        {
            L(0, "func _physics_process(_delta: float) -> void:");
            L(1, "var p := _player() as Node2D");
            L(1, "if p == null:");
            L(2, "return");
            foreach (var t in touches)
            {
                L(1, $"var o{Fn(t)} := _obj({Q(NodeName(t.P("object")))}) as Node2D");
                L(1, $"var on{Fn(t)} := o{Fn(t)} != null and o{Fn(t)}.visible and p.global_position.distance_to(o{Fn(t)}.global_position) < {F(TouchRadius)}");
                L(1, $"if on{Fn(t)} and not _touching.get({Q(t.Id)}, false):");
                L(2, $"{Fn(t)}()");
                L(1, $"_touching[{Q(t.Id)}] = on{Fn(t)}");
            }
            L(0, "");
        }

        L(0, "func _set_state(n: String, s: String) -> void:");
        L(1, "var o := _obj(n)");
        L(1, "if o == null:");
        L(2, "return");
        L(1, "o.set_meta(\"state\", s)");
        L(1, "var anim: String = o.get_meta(\"states\", {}).get(s, s)   # a character maps states to sprite tags");
        L(1, "var spr := (o if o is AnimatedSprite2D else o.find_child(\"AnimatedSprite2D\", true, false)) as AnimatedSprite2D");
        L(1, "if spr and spr.sprite_frames and spr.sprite_frames.has_animation(anim):");
        L(2, "spr.play(anim)");
        foreach (var sc in g.Nodes.Where(n => n.Kind == LogicKind.StateChanged))
        {
            L(1, $"if n == {Q(NodeName(sc.P("object")))} and s == {Q(sc.P("state").Trim())}:");
            L(2, $"{Fn(sc)}()");
        }
        L(0, "");

        foreach (var n in g.Nodes)
        {
            L(0, $"func {Fn(n)}() -> void:   # {n.Kind}");
            string Obj(string key) => $"_obj({Q(NodeName(n.P(key)))})";
            switch (n.Kind)
            {
                case LogicKind.Compare:
                    string op = LogicGraph.CompareOps.Contains(n.P("op").Trim()) ? n.P("op").Trim() : ">=";
                    L(1, $"if float(vars.get({Q(n.P("variable").Trim())}, 0.0)) {op} {Num(n, "value")}:");
                    Calls(2, n, "true");
                    L(1, "else:");
                    Calls(2, n, "false");
                    break;
                case LogicKind.HasItem:
                    L(1, $"if int(items.get({Q(n.P("item").Trim())}, 0)) >= {(int.TryParse(n.P("count"), out int need) ? need : 1)}:");
                    Calls(2, n, "true");
                    L(1, "else:");
                    Calls(2, n, "false");
                    break;
                default:
                    switch (n.Kind)
                    {
                        case LogicKind.SetVariable:
                        {
                            string v = Q(n.P("variable").Trim());
                            L(1, n.P("op").Trim() switch
                            {
                                "+=" => $"vars[{v}] = float(vars.get({v}, 0.0)) + {Num(n, "value")}",
                                "-=" => $"vars[{v}] = float(vars.get({v}, 0.0)) - {Num(n, "value")}",
                                _ => $"vars[{v}] = {Num(n, "value")}",
                            });
                            break;
                        }
                        case LogicKind.GiveItem:
                        {
                            string it = Q(n.P("item").Trim());
                            L(1, $"items[{it}] = max(0, int(items.get({it}, 0)) + {(int.TryParse(n.P("count"), out int c) ? c : 1)})");
                            break;
                        }
                        case LogicKind.PlaySound when Guid.TryParse(n.P("sound"), out var s) && res(s) is string wav:
                            L(1, "var snd := AudioStreamPlayer.new()");
                            L(1, $"snd.stream = load({Q(wav)})");
                            L(1, "add_child(snd)");
                            L(1, "snd.finished.connect(snd.queue_free)");
                            L(1, "snd.play()");
                            break;
                        case LogicKind.Show:
                            bool vis = n.P("visible") == "yes";
                            L(1, $"var o := {Obj("object")}");
                            L(1, "if o:");
                            L(2, $"o.visible = {(vis ? "true" : "false")}");
                            L(2, $"o.process_mode = Node.PROCESS_MODE_{(vis ? "INHERIT" : "DISABLED")}");
                            break;
                        case LogicKind.SetState:
                            L(1, $"_set_state({Q(NodeName(n.P("object")))}, {Q(n.P("state").Trim())})");
                            break;
                        case LogicKind.PlayClip:
                            L(1, $"var o := {Obj("object")}");
                            L(1, "var ap := (o.find_child(\"AnimationPlayer\", true, false) if o else null) as AnimationPlayer");
                            L(1, $"if ap and ap.has_animation({Q(n.P("clip").Trim())}):");
                            L(2, $"ap.play({Q(n.P("clip").Trim())})");
                            break;
                        case LogicKind.Wait:
                            L(1, $"await get_tree().create_timer({F(Math.Max(0, double.Parse(Num(n, "ms"), CultureInfo.InvariantCulture)) / 1000)}).timeout");
                            break;
                        case LogicKind.LoadScene when Guid.TryParse(n.P("scene"), out var sc) && res(sc) is string tscn:
                            L(1, $"get_tree().change_scene_to_file({Q(tscn)})");
                            L(1, "return");
                            sb.Append('\n');
                            continue;
                        case LogicKind.PlaySound or LogicKind.LoadScene:
                            L(1, "push_warning(\"Pixelkiln: the asset of this node was not exported.\")");
                            break;
                    }
                    Calls(1, n, "out");
                    break;
            }
            sb.Append('\n');
        }
        return sb.ToString().TrimEnd('\n') + "\n";
    }
}
